-- =============================================================================
-- 2. conversations — User-scoped chat threads (ConversationManager replacement)
-- =============================================================================
--
-- Access Patterns:
--   list_threads:    SELECT ... WHERE user_id = $1 ORDER BY updated_at DESC
--   get_context:     SELECT messages WHERE thread_id = $1 ORDER BY created_at DESC LIMIT N
--   add_message:     INSERT INTO messages (thread_id, role, content)
--                    UPDATE conversations SET updated_at = NOW() WHERE id = $1
--   delete_thread:   DELETE FROM conversations WHERE id = $1 (CASCADE deletes messages)
--   get_or_create:   SELECT by id + INSERT on miss (or INSERT ... ON CONFLICT DO NOTHING)
--
-- Row Estimates:
--   Threads: bounded at 50 per user (application-enforced). At 1000 users = 50K max.
--   Messages: ~10-50 per active thread. At 50K threads * 20 avg = 1M messages.
--   Message tuple: ~300 B main + TOAST-ed content. 1M rows = ~300 MB + TOAST.
--   Partitioning: NOT warranted at these volumes.

CREATE TABLE IF NOT EXISTS conversations (
    -- Thread identifier. UUID-style string (12-char hex from the app).
    -- Same format as old code: f"th_{uuid.uuid4().hex[:12]}"
    id          VARCHAR(50) PRIMARY KEY,

    -- Owning user. INTEGER from SQLite auth.db users(id).
    -- Cross-database reference — no FK possible.
    -- NOT NULL: every thread belongs to exactly one user.
    user_id     INTEGER NOT NULL,

    -- Display title. Max 50 chars in old code (see conversation.py:148 title[:50]).
    -- We use 100 with a CHECK to allow longer titles if the UI evolves.
    title       VARCHAR(100) NOT NULL DEFAULT '新对话',

    -- Creation timestamp. Set once, never updated.
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Last activity timestamp. Updated on every add_message.
    -- This is the sort key for list_threads.
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Soft constraint: title fits within display limits.
    -- Hard delete is used (no deleted_at); if soft-delete needed later:
    --   ALTER TABLE conversations ADD COLUMN deleted_at TIMESTAMPTZ;
    CONSTRAINT chk_conversations_title_length CHECK (char_length(title) <= 100)
);

-- Index for listing threads by user, newest first.
-- This is the only read query on the conversations table itself.
-- Composite covers WHERE user_id = $1 + ORDER BY updated_at DESC.
CREATE INDEX idx_conversations_user_updated
    ON conversations(user_id, updated_at DESC);


-- =============================================================================
-- 3. messages — Individual messages within a conversation thread
-- =============================================================================
--
-- Normalized rather than JSONB because:
--   1. Messages have structural constraints (role CHECK, content length).
--   2. Append-only — no updates, no partial modifications.
--   3. The JOIN cost is trivial with the thread_id index.
--   4. Future: allows searching across messages if needed.
--   5. Cleaner: PG handles TOAST, ordering, and constraint enforcement;
--      the app doesn't need to validate a JSONB array on every read.

CREATE TABLE IF NOT EXISTS messages (
    -- Synthetic PK. BIGSERIAL gives us 2^63 IDs — effectively unlimited.
    -- We don't need a UUID per message; BIGSERIAL is faster and more compact.
    id          BIGSERIAL PRIMARY KEY,

    -- Parent thread. CASCADE DELETE: when a thread is deleted, all its
    -- messages are automatically removed. Matches old delete_thread behavior.
    thread_id   VARCHAR(50) NOT NULL
                REFERENCES conversations(id) ON DELETE CASCADE,

    -- Message role. Constrained to known values.
    -- 'system' included for future use (e.g., injected system notes).
    role        VARCHAR(10) NOT NULL,

    -- Message content. Max 10000 chars enforced at DB level.
    -- TEXT with a CHECK (not VARCHAR(10000)) because TEXT + CHECK gives
    -- the same constraint without the VARCHAR length overhead in catalogs.
    -- Also, PG stores TEXT and VARCHAR identically internally.
    content     TEXT NOT NULL,

    -- Message timestamp. Used for ordering within a thread.
    -- NOT NULL with DEFAULT NOW() — every message has a timestamp.
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Domain constraints
    CONSTRAINT chk_messages_role CHECK (role IN ('user', 'assistant', 'system')),
    CONSTRAINT chk_messages_content_length CHECK (char_length(content) <= 10000)
);

-- Index for fetching messages by thread, newest first.
-- This covers both:
--   get_context:         WHERE thread_id = $1 ORDER BY created_at DESC LIMIT N
--   get_context_for_rewrite: WHERE thread_id = $1 ORDER BY created_at DESC LIMIT 6
-- The composite index covers the FK lookup AND the ORDER BY.
CREATE INDEX idx_messages_thread_created
    ON messages(thread_id, created_at DESC);

