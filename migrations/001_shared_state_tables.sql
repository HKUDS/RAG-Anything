-- =============================================================================
-- 1. query_history — Immutable audit log of user queries to agents
-- =============================================================================
--
-- Access Patterns:
--   WRITE: 1 INSERT per query (very write-light)
--   READ:  SELECT ... [WHERE user_id = $1] ORDER BY time DESC LIMIT 50
--          Admin dashboard reads only. Filter by user_id is optional.
--
-- Row Estimates:
--   Current cap: 100 entries (agent.py trims to 100). If uncapped, ~1000/day
--   under heavy load. Average row: ~3 KB (answer text TOAST-ed, main tuple ~200 B).
--   100K rows = ~20 MB main data + ~300 MB TOAST. Negligible for PG.
--   Partitioning: NOT warranted. Even at 1M rows this is a small table.

CREATE TABLE IF NOT EXISTS query_history (
    -- Primary key: UUID v4 generated by the app (see agent.py: query_id)
    -- Using TEXT rather than UUID type so the app doesn't need uuid-to-string
    -- conversions and JSON persistence remains source-of-truth compatible.
    id          TEXT PRIMARY KEY,

    -- The user's natural-language query. NOT NULL because every record has one.
    query       TEXT NOT NULL,

    -- Query mode: 'text', 'vision', 'multimodal', 'hybrid'
    -- VARCHAR(20) is generous enough for any future modes.
    mode        VARCHAR(20) NOT NULL DEFAULT 'text',

    -- Agent execution mode: 'none', 'cot', 'react', etc.
    -- VARCHAR(50) covers all known agent modes + future expansion.
    agent_mode  VARCHAR(50) NOT NULL DEFAULT 'none',

    -- Full LLM response. TEXT (unlimited) because LLM answers can be very long
    -- (multi-paragraph with citations). Stored as TOAST (out-of-line) automatically
    -- by PG when exceeding ~2 KB.
    answer      TEXT NOT NULL DEFAULT '',

    -- Structured reasoning trace: {"steps": [...], "total_steps": N}
    -- JSONB for indexable/queryable structured data.
    -- Default '{}' rather than NULL so consumers never need null checks.
    reasoning_trace JSONB NOT NULL DEFAULT '{}',

    -- Image references produced or consumed during the query.
    -- JSONB array: ["url1", "url2", ...]
    images      JSONB NOT NULL DEFAULT '[]',

    -- When the query was recorded. TIMESTAMPTZ stores absolute UTC with zone info.
    -- This is the primary sort key for the dashboard.
    time        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Query latency in seconds. REAL (float4, 6 decimal digits) is sufficient
    -- for elapsed time; we don't need microsecond precision.
    elapsed     REAL NOT NULL DEFAULT 0,

    -- Knowledge base name used for this query.
    -- VARCHAR(255) matches typical KB name lengths.
    kb          VARCHAR(255) NOT NULL DEFAULT '',

    -- Agent identifier (UUID string, e.g. "a1b2c3d4")
    agent_id    VARCHAR(50) NOT NULL DEFAULT '',

    -- Conversation thread identifier (UUID string)
    thread_id   VARCHAR(50) NOT NULL DEFAULT '',

    -- User who made the query. INTEGER matches SQLite auth.db users(id).
    -- Cross-database reference — no FK possible. Application enforces integrity.
    -- NOT NULL because every query belongs to a user.
    user_id     INTEGER NOT NULL,

    -- Denormalized username for display efficiency.
    -- Saves a JOIN/auth.db round-trip on every dashboard render.
    -- VARCHAR(255) per RFC 3696 errata for email-as-username scenarios.
    username    VARCHAR(255) NOT NULL DEFAULT '',

    -- Whether the LLM fell back to a degraded mode (no KB context available).
    fallback    BOOLEAN NOT NULL DEFAULT FALSE
);

-- -------------------------------------------------------------------------
-- Index Strategy for query_history
-- -------------------------------------------------------------------------
-- Query 1 (user-filtered, 99% of non-admin reads):
--   SELECT * FROM query_history
--   WHERE user_id = $1 ORDER BY time DESC LIMIT 50;
-- Covered by: idx_query_history_user_time

-- Query 2 (admin: all users, no filter):
--   SELECT * FROM query_history ORDER BY time DESC LIMIT 50;
-- Covered by: idx_query_history_time

-- Query 3 (future: filter by agent_id):
--   SELECT * FROM query_history WHERE agent_id = $1 ORDER BY time DESC;
-- Partially covered by idx_query_history_time (can filter on agent_id with
-- index cond), but if agent-scoped queries become frequent, add:
--   CREATE INDEX idx_query_history_agent_time ON query_history(agent_id, time DESC);

-- Composite index for user-filtered queries (covers the WHERE + ORDER BY + LIMIT
-- pattern completely — index-only scan possible if SELECT list is narrow).
CREATE INDEX idx_query_history_user_time
    ON query_history(user_id, time DESC);

-- Standalone time index for admin "all users" queries.
-- Separate from the composite because a query without user_id filter
-- cannot use the leading column of idx_query_history_user_time efficiently.
CREATE INDEX idx_query_history_time
    ON query_history(time DESC);

