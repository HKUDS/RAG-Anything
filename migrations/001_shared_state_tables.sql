-- =============================================================================
-- 5. Utility: auto-update updated_at trigger (optional convenience)
-- =============================================================================
--
-- Keeps conversations.updated_at in sync without application code.
-- Alternative: update updated_at explicitly in the add_message transaction.
-- Using a trigger eliminates the risk of forgetting the UPDATE.

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Attach trigger to conversations table.
-- Fires BEFORE UPDATE: any UPDATE to conversations auto-refreshes updated_at.
DROP TRIGGER IF EXISTS trg_conversations_updated_at ON conversations;
CREATE TRIGGER trg_conversations_updated_at
    BEFORE UPDATE ON conversations
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

COMMIT;

